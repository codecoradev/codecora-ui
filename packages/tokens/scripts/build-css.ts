// Writes dist/css/theme.css, the package's one stylesheet. Run by `bun run build`.
import { mkdirSync, writeFileSync } from 'node:fs';
import { tailwindThemeCss } from '../src/tailwind.js';

const out = new URL('../dist/css/', import.meta.url);
mkdirSync(out, { recursive: true });

const header = '/* @codecora/tokens: generated by scripts/build-css.ts, do not edit. */\n';
writeFileSync(new URL('theme.css', out), header + tailwindThemeCss());
console.log('dist/css/theme.css');

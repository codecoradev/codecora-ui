// Writes the CSS outputs to dist/css. Run by `bun run build`.
import { mkdirSync, writeFileSync } from 'node:fs';
import { baseCss, shadcnCss, tailwindCss, themeCss } from '../src/css.js';
import { themeNames } from '../src/schema.js';
import { themes } from '../src/themes.js';

const out = new URL('../dist/css/', import.meta.url);
mkdirSync(new URL('themes/', out), { recursive: true });

const header = '/* @codecora/tokens: generated by scripts/build-css.ts, do not edit. */\n';
const write = (path: string, css: string) => writeFileSync(new URL(path, out), header + css);

const base = baseCss();
const perTheme = themeNames.map((name) => themeCss(themes[name]));

write('base.css', base);
themeNames.forEach((name, i) => write(`themes/${name}.css`, perTheme[i]!));
write('tokens.css', [base, ...perTheme].join('\n'));
write('tailwind.css', tailwindCss());
write('shadcn.css', shadcnCss());
console.log(`dist/css: base, tokens, tailwind, shadcn, themes/{${themeNames.join(',')}}`);
